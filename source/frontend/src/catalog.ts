export const pathFor = (id: string, target = "current") => {
  const found = pages.find((p) => p.id === id);
  if (!found) return "/not-found";
  return found.path.replace(":id", target);
};

export const pathForFeature = (
  system: SystemId,
  feature: string,
  target = "current",
) => {
  const found = pages.find((p) => p.system === system && p.feature === feature);
  return found ? found.path.replace(":id", target) : "/not-found";
};

